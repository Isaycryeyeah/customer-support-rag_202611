def build_high_risk_refusal(risk_types: List[str], query: str = '') -> str:
    if any(word in query for word in ('充电器', '插头', '插座')):
        return """结论：
充电器、插头或插座出现异常发热、冒烟等情况时，应停止充电并优先确保人身安全。不要拆解或改装充电器。

处理步骤：
1. 在能够安全操作的前提下切断电源；不要触碰冒烟、起火或损坏的插头、插座，也不要强行拔插。无法安全断电时应远离并寻求专业或应急帮助。
2. 不要反复插拔、通电测试，也不要继续使用异常充电器。
3. 联系官方售后或专业人员检查设备、充电器和供电部位；如有冒烟、起火或人身危险，应远离并联系当地应急服务。

注意事项：
- 优先使用原装或经认证的充电器和数据线。非官方配件可能无法触发快充或存在兼容性风险，劣质或来源不明的配件还可能带来发热、损坏和安全风险。
- 不要自行拆卸、挤压、刺破、加热或短接，也不要尝试通过改装提高充电速度。
- 当前提供安全提示和人工处理建议，尚未实际派单。

引用来源：
- 预设安全提示规则（参考充电器安全使用说明、快充安全使用说明；非本次检索结果）。
"""
    if "dangerous_repair" in risk_types:
        notice = DANGEROUS_OPERATION_NOTICE
    else:
        notice = BATTERY_SAFETY_NOTICE

    return f"""结论：
{notice}

处理步骤：
1. 优先确保人身安全，停止使用设备；在能够安全操作的前提下切断电源，不要触碰已冒烟或起火的设备。
2. 不要自行拆卸、挤压、刺破、加热或短接处理。
3. 联系官方售后服务中心，由专业人员进行检测和处理。

注意事项：
- 该问题涉及安全风险，建议优先联系人工售后；当前仅提供处理建议，尚未实际派单。
- 如出现冒烟、异味或起火，请远离设备并及时报警。

引用来源：
- 安全风险识别规则（非文档检索结果）。
"""

"""Repack a trusted installed distribution for an isolated local install, verifying RECORD hashes.

Fallback for a stalled wheel download. Not a vendor-original wheel and not for redistribution.
Console scripts are regenerated by pip from entry_points.txt in the destination environment.
"""
import argparse
import base64
import csv
import hashlib
from importlib import metadata
import io
import json
from pathlib import Path
import zipfile


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('package')
    p.add_argument('--output',required=True)
    args=p.parse_args()
    dist=metadata.distribution(args.package)
    root=Path(dist.locate_file('')).resolve()
    wheel=dist.read_text('WHEEL')
    tag=next(line.split(': ',1)[1] for line in wheel.splitlines() if line.startswith('Tag: '))
    name=dist.metadata['Name'].replace('-','_')
    out=Path(args.output);out.mkdir(parents=True,exist_ok=True)
    target=out/f'{name}-{dist.version}-{tag}.whl'
    records=[];verified=0
    with zipfile.ZipFile(target,'w',zipfile.ZIP_DEFLATED,compresslevel=1,allowZip64=True) as z:
        for entry in dist.files or []:
            source=Path(dist.locate_file(entry)).resolve()
            if not source.is_relative_to(root) or not source.is_file() or source.suffix=='.pyc':continue
            relative=source.relative_to(root).as_posix()
            if relative.endswith(('/RECORD','/INSTALLER','/REQUESTED','/direct_url.json','/RECORD.jws','/RECORD.p7s')):continue
            with source.open('rb') as f:digest=hashlib.file_digest(f,'sha256').digest()
            encoded=base64.urlsafe_b64encode(digest).rstrip(b'=').decode()
            if entry.hash and entry.hash.mode=='sha256':
                if encoded!=entry.hash.value:raise ValueError(f'Installed file differs from original RECORD: {relative}')
                verified+=1
            z.write(source,relative)
            records.append((relative,'sha256='+encoded,source.stat().st_size))
        record_name=f'{name}-{dist.version}.dist-info/RECORD'
        stream=io.StringIO();writer=csv.writer(stream,lineterminator='\n')
        writer.writerows(records);writer.writerow((record_name,'',''))
        z.writestr(record_name,stream.getvalue())
    report={'package':name,'version':dist.version,'files':len(records),'original_record_verified_files':verified,
            'wheel_sha256':hashlib.sha256(target.read_bytes()).hexdigest(),
            'provenance':'locally repacked trusted installation; not vendor-original wheel',
            'bytes':target.stat().st_size}
    target.with_suffix('.provenance.json').write_text(json.dumps(report,indent=2),encoding='utf-8')
    print(json.dumps(report,indent=2),flush=True)


if __name__=='__main__':main()
